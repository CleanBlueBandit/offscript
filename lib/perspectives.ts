/** Partial Fisher–Yates shuffle: every eligible lens has equal probability; the pool stays unchanged. */
export function drawPerspectives(
  count = 15,
  excludeIds: string[] = [],
): Perspective[] {
  const excluded = new Set(excludeIds);
  const pool = PERSPECTIVES.filter(
    (perspective) => !excluded.has(perspective.id),
  );
  const take = Math.max(
    0,
    Math.min(Number.isFinite(count) ? Math.floor(count) : 0, pool.length),
  );
  for (let index = 0; index < take; index += 1) {
    const randomIndex =
      index + Math.floor(Math.random() * (pool.length - index));
    [pool[index], pool[randomIndex]] = [pool[randomIndex], pool[index]];
  }
  return pool.slice(0, take);
}

/** Spread a small first batch across families; mix task relevance with new lenses. */
export function selectPerspectives(
  count = 6,
  excludeIds: string[] = [],
  brief?: Brief,
): Perspective[] {
  const pool = drawPerspectives(PERSPECTIVES.length, excludeIds);
  const take = Math.max(
    0,
    Math.min(Number.isFinite(count) ? Math.floor(count) : 0, pool.length),
  );
  const query =
    `${brief?.challenge || ""} ${brief?.targetUser || ""} ${brief?.moment || ""} ${brief?.observations || ""}`.toLowerCase();
  const terms = [...new Set(query.match(/[a-z]{4,}/g) || [])];
  const relevance = (lens: Perspective) => {
    const content = `${lens.name} ${lens.axiom} ${lens.operator}`.toLowerCase();
    return terms.filter((term) => content.includes(term)).length;
  };
  const chosen: Perspective[] = [];
  const counts = new Map<Category, number>();
  while (chosen.length < take) {
    const leastUsed = Math.min(
      ...pool.map((lens) => counts.get(lens.category) || 0),
    );
    const candidates = pool.filter(
      (lens) => (counts.get(lens.category) || 0) === leastUsed,
    );
    // The shuffled order breaks ties. Alternating relevance and discovery avoids
    // returning only literal matches to the problem's vocabulary.
    if (chosen.length % 2 === 0)
      candidates.sort((a, b) => relevance(b) - relevance(a));
    const next = candidates[0];
    chosen.push(next);
    counts.set(next.category, (counts.get(next.category) || 0) + 1);
    pool.splice(pool.indexOf(next), 1);
  }
  return chosen;
}
